#!/usr/bin/env python3
"""Generates satellite_icon.c: the watch face's GPS icon as an LVGL A8 (alpha-only) image.

The face tints it with the image recolor style. Shapes are drawn upright (panels left and right,
dish on top), rotated 45 degrees, and antialiased by supersampling.

    python3 tools/make_satellite_icon.py > satellite_icon.c
"""
import math

SIZE = 30
SCALE = SIZE / 22  # shapes below are in units of a 22 px icon
SAMPLES = 6  # per axis, per pixel
ANGLE = math.radians(-45)


def inside(u, v):
    if abs(u) <= 2.6 and abs(v) <= 3.2:  # body
        return True
    if 2.6 < abs(u) <= 4.0 and abs(v) <= 0.7:  # struts
        return True
    if 4.0 < abs(u) <= 9.6 and abs(v) <= 3.4:  # solar panels, split into two cells each
        return abs(abs(u) - 6.8) > 0.45
    if abs(u) <= 0.6 and -5.6 <= v < -3.2:  # antenna mast
        return True
    return v <= -5.6 and u * u + (v + 5.6) ** 2 <= 2.8 ** 2  # dish


def pixel(x, y):
    hits = 0
    for sy in range(SAMPLES):
        for sx in range(SAMPLES):
            px = x + (sx + 0.5) / SAMPLES - SIZE / 2
            py = y + (sy + 0.5) / SAMPLES - SIZE / 2
            u = (px * math.cos(ANGLE) + py * math.sin(ANGLE)) / SCALE
            v = (-px * math.sin(ANGLE) + py * math.cos(ANGLE)) / SCALE
            hits += inside(u, v)
    return round(255 * hits / SAMPLES ** 2)


rows = [[pixel(x, y) for x in range(SIZE)] for y in range(SIZE)]
print("// Generated by tools/make_satellite_icon.py; edit that and regenerate.")
print('#include "lvgl.h"\n')
print("static const uint8_t satellite_icon_map[] = {")
for row in rows:
    print("    " + ", ".join(f"0x{a:02x}" for a in row) + ",")
print("};\n")
print("const lv_image_dsc_t satellite_icon = {")
print(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE}}},")
print("    .data_size = sizeof(satellite_icon_map),")
print("    .data = satellite_icon_map,")
print("};")
