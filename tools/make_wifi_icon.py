#!/usr/bin/env python3
"""Generates wifi_icon.c: the watch face's Wi-Fi icons as LVGL A8 (alpha-only) images.

The usual fan of a dot and three arcs, one image per signal level: wifi_icon_1 lights only the dot,
wifi_icon_4 everything. Unlit parts are kept faint so the full shape stays visible. Like the
satellite icon, the face tints them with the image recolor style. Antialiased by supersampling.

    python3 tools/make_wifi_icon.py > wifi_icon.c
"""
import math

SIZE = 30
SAMPLES = 6  # per axis, per pixel
UNLIT = 0.28  # alpha of parts above the current level
HALF_ANGLE = math.radians(45)  # each arc spans 45 degrees either side of straight up
CY = 25.0  # fan center (bottom middle), in pixels
DOT_R = 3.0
ARCS = [(6.2, 9.4), (12.0, 15.2), (17.8, 21.0)]  # inner and outer radius of each arc


def part(x, y):
    """Which part a point is in: 0 the dot, 1-3 the arcs, None for empty."""
    dx, dy = x - SIZE / 2, CY - y
    r = math.hypot(dx, dy)
    if r <= DOT_R:
        return 0
    if dy <= 0 or abs(math.atan2(dx, dy)) > HALF_ANGLE:
        return None
    for i, (inner, outer) in enumerate(ARCS):
        if inner <= r <= outer:
            return i + 1
    return None


def pixel(x, y, level):
    total = 0.0
    for sy in range(SAMPLES):
        for sx in range(SAMPLES):
            p = part(x + (sx + 0.5) / SAMPLES, y + (sy + 0.5) / SAMPLES)
            if p is not None:
                total += 1.0 if p < level else UNLIT
    return round(255 * total / SAMPLES ** 2)


print("// Generated by tools/make_wifi_icon.py; edit that and regenerate.")
print('#include "lvgl.h"')
for level in range(1, 5):
    rows = [[pixel(x, y, level) for x in range(SIZE)] for y in range(SIZE)]
    print(f"\nstatic const uint8_t wifi_icon_{level}_map[] = {{")
    for row in rows:
        print("    " + ", ".join(f"0x{a:02x}" for a in row) + ",")
    print("};\n")
    print(f"const lv_image_dsc_t wifi_icon_{level} = {{")
    print(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE}}},")
    print(f"    .data_size = sizeof(wifi_icon_{level}_map),")
    print(f"    .data = wifi_icon_{level}_map,")
    print("};")
