#!/usr/bin/env python3
"""Generates steps_icon.c: the launcher's Steps icon, two footprints, as an LVGL A8 (alpha-only) image.

Each footprint is an oval sole and a round heel, tilted outward; the right foot is a step ahead of
the left. The launcher tints it black with the image recolor style. Antialiased by supersampling.

    python3 tools/make_steps_icon.py > steps_icon.c
"""
import math

SIZE = 44
SAMPLES = 6  # per axis, per pixel
# Foot centers (between sole and heel) and tilt; each foot is drawn in its own upright frame.
FEET = [(13.0, 26.0, math.radians(-10)), (31.0, 18.0, math.radians(10))]
SOLE = (0.0, -6.0, 6.2, 9.0)  # center u, v and radii, relative to the foot center
HEEL = (0.0, 9.6, 4.6, 5.0)


def in_ellipse(u, v, e):
    cu, cv, ru, rv = e
    return ((u - cu) / ru) ** 2 + ((v - cv) / rv) ** 2 <= 1


def inside(x, y):
    for fx, fy, angle in FEET:
        dx, dy = x - fx, y - fy
        u = dx * math.cos(angle) + dy * math.sin(angle)
        v = -dx * math.sin(angle) + dy * math.cos(angle)
        if in_ellipse(u, v, SOLE) or in_ellipse(u, v, HEEL):
            return True
    return False


def pixel(x, y):
    hits = sum(inside(x + (sx + 0.5) / SAMPLES, y + (sy + 0.5) / SAMPLES)
               for sy in range(SAMPLES) for sx in range(SAMPLES))
    return round(255 * hits / SAMPLES ** 2)


print("// Generated by tools/make_steps_icon.py; edit that and regenerate.")
print('#include "lvgl.h"')
print("\nstatic const uint8_t steps_icon_map[] = {")
for y in range(SIZE):
    print("    " + ", ".join(f"0x{pixel(x, y):02x}" for x in range(SIZE)) + ",")
print("};\n")
print("const lv_image_dsc_t steps_icon = {")
print(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE}}},")
print("    .data_size = sizeof(steps_icon_map),")
print("    .data = steps_icon_map,")
print("};")
