#!/usr/bin/env python3
"""Generates weather_icons.c: the Weather app's condition icons as LVGL A4 (4-bit alpha-only) images.

Each icon is one or two layers that the app stacks and tints separately (say, a yellow sun behind
a white cloud). Every layer is made in two sizes, BIG for the current conditions and SMALL for the
forecasts, and listed in weather_icon_layers[size][icon][layer] (NULL when an icon has one layer),
in the order of the WeatherIcon enum in weather_app.cpp. weather_app_icon, for the launcher, is the
partly cloudy icon in one layer. Shapes are drawn on a 24-unit grid and antialiased by supersampling;
16 alpha levels look the same as 256 at these sizes and take half the flash.

    python3 tools/make_weather_icons.py > weather_icons.c
"""
import math

SIZES = {"big": 88, "small": 40}
LAUNCHER_SIZE = 46
SAMPLES = 4  # per axis, per pixel


def circle(cx, cy, r):
    return lambda x, y: (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def segment(x1, y1, x2, y2, w):
    """A line with round ends, w units wide."""
    def inside(x, y):
        dx, dy = x2 - x1, y2 - y1
        t = max(0.0, min(1.0, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
        return (x - x1 - t * dx) ** 2 + (y - y1 - t * dy) ** 2 <= (w / 2) ** 2
    return inside


def union(*shapes):
    return lambda x, y: any(s(x, y) for s in shapes)


def minus(a, b):
    return lambda x, y: a(x, y) and not b(x, y)


def polygon(points):
    def inside(x, y):
        hit = False
        for (x1, y1), (x2, y2) in zip(points, points[1:] + points[:1]):
            if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
                hit = not hit
        return hit
    return inside


def sun(cx, cy, s):
    rays = [segment(cx + 7 * s * math.cos(a), cy + 7 * s * math.sin(a),
                    cx + 10 * s * math.cos(a), cy + 10 * s * math.sin(a), 1.8 * s)
            for a in (i * math.pi / 4 for i in range(8))]
    return union(circle(cx, cy, 4.6 * s), *rays)


def moon(cx, cy, s):
    return minus(circle(cx, cy, 8 * s), circle(cx + 4.5 * s, cy - 3.5 * s, 7 * s))


def cloud(cx, cy, s, grow=0.0):
    """Three bumps over a flat bottom; `grow` widens it to cut a gap in what's behind."""
    g = grow
    return union(circle(cx - 4.5 * s, cy + 1.5 * s, 3.5 * s + g),
                 circle(cx, cy - 1.5 * s, 5 * s + g),
                 circle(cx + 4.8 * s, cy + 1.2 * s, 3.8 * s + g),
                 lambda x, y: cx - 4.5 * s <= x <= cx + 4.8 * s and cy + 1.2 * s <= y <= cy + 5 * s + g)


def peeking(body):
    """A small sun or moon at the top left, partly behind a cloud at the bottom right."""
    return [minus(body, cloud(14.5, 15, 0.95, grow=1.3)), cloud(14.5, 15, 0.95)]


UPPER_CLOUD = cloud(12, 9.5, 1.0)
ICONS = [  # same order as WeatherIcon in weather_app.cpp
    ("clear_day", [sun(12, 12, 1.0)]),
    ("clear_night", [moon(12, 12, 1.0)]),
    ("partly_day", peeking(sun(8.5, 8.5, 0.72))),
    ("partly_night", peeking(moon(8.5, 8.5, 0.62))),
    ("cloudy", [cloud(12, 13, 1.15)]),
    ("fog", [cloud(12, 9, 0.9), union(*(segment(4.5, y, 19.5, y, 1.6) for y in (16.5, 19.5, 22.5)))]),
    ("rain", [UPPER_CLOUD, union(*(segment(x + 1.2, 16.5, x - 0.6, 21.5, 1.6) for x in (7.5, 12, 16.5)))]),
    ("snow", [UPPER_CLOUD, union(*(circle(x, y, 1.5) for x, y in ((7.5, 18), (12, 21.5), (16.5, 18))))]),
    ("thunder", [UPPER_CLOUD, polygon([(13.4, 13), (8.6, 19.2), (11.8, 19.2), (10.2, 23.6),
                                       (16, 16.6), (12.8, 16.6), (14.8, 13)])]),
]


def render(shape, size):
    """Rows of bytes, two pixels per byte with the left one in the high nibble (sizes are even)."""
    unit = 24 / size
    rows = []
    for y in range(size):
        alphas = [round(15 * sum(shape((x + (sx + 0.5) / SAMPLES) * unit, (y + (sy + 0.5) / SAMPLES) * unit)
                                 for sy in range(SAMPLES) for sx in range(SAMPLES)) / SAMPLES ** 2)
                  for x in range(size)]
        rows.append([alphas[x] << 4 | alphas[x + 1] for x in range(0, size, 2)])
    return rows


def image(var, rows, size, public=False):
    print(f"\nstatic const uint8_t {var}_map[] = {{")
    for row in rows:
        print("    " + ",".join(f"0x{a:02x}" for a in row) + ",")
    print("};")
    print(f"{'' if public else 'static '}const lv_image_dsc_t {var} = {{")
    print(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A4, .flags = 0, .w = {size}, .h = {size}, .stride = {size // 2}}},")
    print(f"    .data_size = sizeof({var}_map),")
    print(f"    .data = {var}_map,")
    print("};")


print("// Generated by tools/make_weather_icons.py; edit that and regenerate.")
print('#include "lvgl.h"')
for size_name, size in SIZES.items():
    for name, layers in ICONS:
        for i, shape in enumerate(layers):
            image(f"wx_{size_name}_{name}_{i}", render(shape, size), size)
image("weather_app_icon", render(union(*dict(ICONS)["partly_day"]), LAUNCHER_SIZE), LAUNCHER_SIZE, public=True)

print(f"\nconst lv_image_dsc_t *const weather_icon_layers[{len(SIZES)}][{len(ICONS)}][2] = {{")
for size_name in SIZES:
    print("    {")
    for name, layers in ICONS:
        refs = [f"&wx_{size_name}_{name}_{i}" for i in range(len(layers))] + ["NULL"] * (2 - len(layers))
        print(f"        {{{', '.join(refs)}}},")
    print("    },")
print("};")
